#!/usr/bin/env python3
"""Build a deterministic test, documentation, profiling, and delta index.

The quality index is intentionally an audit and triage product.  It reports
what can be proven from the source tree, optional coverage profiles, and Git
metadata; it does not turn heuristics into a claim that a repository is 100%
covered.  The output is safe to regenerate for any local folder, including a
folder that is not a Git worktree.
"""
