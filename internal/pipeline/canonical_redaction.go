package pipeline

import (
	"crypto/sha256"
	"encoding/hex"

	"github.com/neuroforge-io/RKC/internal/docparse"
	"github.com/neuroforge-io/RKC/internal/security/secrets"
	"github.com/neuroforge-io/RKC/pkg/rkcmodel"
)

// sanitizeCanonicalBundle preserves only receipt copies already bound to typed
// artifact metadata. Arbitrary attributes, including similarly named digest
// fields, remain payload: they must not gain an exemption by choosing a key.
func sanitizeCanonicalBundle(bundle *rkcmodel.Bundle, literals []string) {
	artifacts := make(map[string]int, len(bundle.Artifacts))
	for index, artifact := range bundle.Artifacts {
		artifacts[artifact.ID] = index
	}
	type documentReceipt struct {
		document, artifact int
		digest             string
	}
	var receipts []documentReceipt
	for index, document := range bundle.Documents {
		if document.Kind != "source_document" || (document.Generator != docparse.PluginID && document.Generator != docparse.SourcePluginID) {
			continue
		}
		id, _ := document.Attributes["artifact_id"].(string)
		artifactIndex, ok := artifacts[id]
		if !ok {
			continue
		}
		artifact := bundle.Artifacts[artifactIndex]
		if document.Path != artifact.Path || document.Attributes["source_sha256"] != artifact.SHA256 {
			continue
		}
		digest, err := hex.DecodeString(artifact.SHA256)
		if err == nil && len(digest) == sha256.Size {
			receipts = append(receipts, documentReceipt{index, artifactIndex, artifact.SHA256})
		}
	}
	secrets.SanitizeBundle(bundle, literals)
	// These three inventory-node attributes are generated by artifactNode and
	// updateArtifactNodes. Rebuild them from the sanitized canonical artifact,
	// without exempting any other map or attribute from payload redaction.
	for index := range bundle.Nodes {
		node := &bundle.Nodes[index]
		artifactIndex, ok := artifacts[node.ID]
		if !ok || bundle.Artifacts[artifactIndex].ID != node.ID {
			continue
		}
		artifact := bundle.Artifacts[artifactIndex]
		if node.Attributes == nil {
			node.Attributes = map[string]any{}
		}
		node.Attributes["sha256"] = artifact.SHA256
		node.Attributes["status"] = artifact.Status
		node.Attributes["size_bytes"] = artifact.SizeBytes
	}
	for _, receipt := range receipts {
		document := &bundle.Documents[receipt.document]
		artifact := bundle.Artifacts[receipt.artifact]
		if document.Attributes["artifact_id"] == artifact.ID && artifact.SHA256 == receipt.digest {
			document.Attributes["source_sha256"] = receipt.digest
		}
	}
}
